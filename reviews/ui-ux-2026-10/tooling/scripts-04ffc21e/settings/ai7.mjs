import { open, audit, go, mainText, info } from "./lib.mjs";
const inf = await info();
const { browser, ctx, page } = await open();
await go(page, "#settings/ai");
const d = page.locator("[role=dialog]");
await page.getByRole("button", { name: "Add an account" }).click(); await page.waitForTimeout(1200);
await d.getByText("More options").click(); await page.waitForTimeout(600);
await d.getByRole("radio", { name: /^Another service that speaks/ }).click(); await page.waitForTimeout(1000);
console.log("inputs:", await d.locator("input, select").evaluateAll(i => i.map(x => `${x.type} ${x.id} ${x.getAttribute("aria-label")||""} ${x.closest("label")?.innerText?.slice(0,40)||""}`)));
// nonsense address first
const addr = d.getByRole("textbox", { name: "Service address" });
await addr.fill("not a web address"); await addr.press("Tab"); await page.waitForTimeout(3000);
console.log("nonsense addr:", (await d.innerText()).split("More options")[1]?.slice(0, 900));
await audit(page, "ai-add-other-badaddr");
await addr.fill(inf.ai_base_url);
await d.locator("#ai-key, input[type=password]").first().fill("another-key"); await page.waitForTimeout(400);
await addr.focus(); await d.locator("input[type=password]").first().focus(); await page.waitForTimeout(3500);
await d.getByRole("radio", { name: /^A backup/ }).click().catch(e => console.log("no backup radio"));
const nm = d.getByRole("textbox", { name: "Name it" });
if (await nm.count()) await nm.fill("Spare AI");
await d.getByRole("button", { name: "Check", exact: true }).click(); await page.waitForTimeout(4000);
console.log("after check:", (await d.innerText()).split("Leave it empty if the service needs none.")[1]?.slice(0, 300));
console.log("add disabled?", await d.getByRole("button", { name: "Add and check" }).isDisabled());
await audit(page, "ai-add-other-filled");
console.log("filled:", (await d.innerText()).split("More options")[1]?.slice(0, 1500));
await d.getByRole("button", { name: "Add and check" }).click(); await page.waitForTimeout(6000);
console.log("dialog still?", await d.count());
if (await d.count()) console.log((await d.innerText()).slice(-800));
console.log("MAIN:", (await mainText(page)).split("AI accounts")[1]?.split("Choose which")[0]);
console.log("toasts:", (await page.locator("[role=status],[role=alert]").allInnerTexts()).join(" | "));
await audit(page, "ai-two-accounts");
await browser.close();
