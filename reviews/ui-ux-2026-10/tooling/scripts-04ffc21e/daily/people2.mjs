import { open, go, audit, mainText, info } from "../../lib.mjs";
const { browser, page } = await open({});
await go(page, "#records/people");
const add = async (full, first, rel, other) => {
  await page.getByRole("button", { name: "Add a person" }).first().click(); await page.waitForTimeout(700);
  const d = page.locator("[role=dialog]");
  await d.getByLabel("Full name", { exact: true }).fill(full);
  if (first) await d.getByLabel(/^First name/).fill(first);
  if (rel) await d.getByLabel(/Who they are to you/).fill(rel);
  if (other) await d.getByLabel(/Other names/).fill(other);
  await d.getByRole("button", { name: "Add a person" }).click(); await page.waitForTimeout(1500);
  console.log("after add", full, "->", page.url().split("#")[1], (await mainText(page)).slice(0, 200).replace(/\n+/g, " | "));
  await go(page, "#records/people");
};
await add("Priya Hart", "", "my sister", "Pri");
await add("Sam Okoro", "", "our neighbor", "");
await add("Rosa Delgado", "Ms. Delgado", "my son's teacher", "");
