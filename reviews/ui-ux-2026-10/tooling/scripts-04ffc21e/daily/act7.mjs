import { open, go, audit, mainText, info } from "../../lib.mjs";
const { browser, ctx, page } = await open({});
await ctx.grantPermissions(["clipboard-read", "clipboard-write"]);
await go(page, "#today");
const line = (t) => page.locator("[data-queue-line]").filter({ hasText: t }).first();
let L = line("Send 2 to-dos to Sam");
await L.getByRole("button", { name: "Review & copy" }).click(); await page.waitForTimeout(1000);
await audit(page, "a7-sam-review", { full: false });
console.log("SAM:", (await L.innerText()).slice(0, 1500));
console.log("SAM textarea:", await L.locator("textarea").first().inputValue().catch(()=>"-"));
await L.getByRole("tab", { name: "Table" }).or(L.getByRole("button", { name: "Table", exact: true })).first().click().catch(()=>{}); await page.waitForTimeout(800);
await audit(page, "a7-sam-table", { full: false });
console.log("TABLE:", (await L.innerText()).slice(0, 1200));
await page.reload(); await page.waitForTimeout(2000);
L = line("Follow up with Priya");
await L.getByRole("button", { name: "Draft a nudge" }).click(); await page.waitForTimeout(1500);
await audit(page, "a7-nudge", { full: false });
console.log("NUDGE:", (await L.innerText()).slice(0, 1500));
await L.getByRole("button", { name: "Followed up" }).click().catch(e=>console.log("no followed up")); await page.waitForTimeout(1500);
await audit(page, "a7-followed-up", { full: false });
console.log("AFTER FOLLOWED UP:", (await mainText(page)).slice(0, 1200));
await browser.close();
