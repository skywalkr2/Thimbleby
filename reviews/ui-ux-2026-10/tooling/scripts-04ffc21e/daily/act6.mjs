import { open, go, audit, mainText, info } from "../../lib.mjs";
const { browser, page } = await open({});
await go(page, "#today");
const line = (t) => page.locator("[data-queue-line]").filter({ hasText: t }).first();
let L = line("Should the dinner be a surprise");
await L.getByRole("button", { name: /More actions/ }).click().catch(async()=>{ await L.click({position:{x:200,y:10}}); await page.waitForTimeout(800); await page.locator("[data-queue-line] button[aria-label*='ore']").first().click(); });
await page.waitForTimeout(600);
await page.getByRole("menuitem", { name: /^Reword/ }).click(); await page.waitForTimeout(1000);
await audit(page, "a6-reword", { full: false });
console.log("REWORD:", (await L.innerText()).replace(/\n+/g, " | "));
await page.keyboard.press("Escape"); await page.reload(); await page.waitForTimeout(2000);
L = line("Should the dinner be a surprise");
await L.click({position:{x:200,y:10}}); await page.waitForTimeout(800);
await L.locator("button[aria-label*='ore']").first().click(); await page.waitForTimeout(600);
await page.getByRole("menuitem", { name: /^Ask someone else/ }).click(); await page.waitForTimeout(1000);
await audit(page, "a6-ask-someone", { full: false });
console.log("ASK ELSE:", (await L.innerText()).replace(/\n+/g, " | "));
await page.reload(); await page.waitForTimeout(2000);
L = line("Should the dinner be a surprise");
await L.getByRole("button", { name: "Answer", exact: true }).first().click(); await page.waitForTimeout(800);
await L.locator("textarea").first().fill("Yes, keep it a surprise. Only Dad knows.");
await L.getByRole("button", { name: "Answer", exact: true }).last().click(); await page.waitForTimeout(2000);
await audit(page, "a6-answered", { full: false });
console.log("ANSWERED:", (await mainText(page)).slice(0, 900));
await browser.close();
