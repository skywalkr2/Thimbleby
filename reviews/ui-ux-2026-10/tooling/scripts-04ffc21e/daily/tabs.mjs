import { open, go, audit, mainText, info } from "../../lib.mjs";
const [mode, pre="t"] = process.argv.slice(2);
const cfg = { d: { width: 1440, height: 900, scheme: "light" }, n: { width: 1440, height: 900, scheme: "dark" }, p: { width: 390, height: 844, scheme: "light" } }[mode];
const { browser, page } = await open(cfg);
const P = (n) => `${pre}-${mode}-${n}`;
const S = async (name, fn) => { try { await fn(); await page.waitForTimeout(900); await audit(page, P(name), { full: mode!=="d" }); console.log((await mainText(page)).slice(0, 600).replace(/\n+/g," | ")); } catch (e) { console.log("FAIL", name, e.message.split("\n")[0]); } };
await go(page, "#schedule");
for (const v of ["Day","Week","Month","Work week"]) await S("sched-"+v.replace(" ",""), () => page.getByRole("button", { name: v, exact: true }).or(page.getByRole("tab", { name: v, exact: true })).or(page.getByRole("radio", { name: v, exact: true })).first().click());
await S("sched-next", () => page.getByRole("button", { name: /next|later|forward/i }).first().click());
await S("sched-prev2", async () => { const b = page.getByRole("button", { name: /previous|earlier|back/i }).first(); await b.click(); await page.waitForTimeout(300); await b.click(); });
await S("sched-today", () => page.getByRole("button", { name: "Today", exact: true }).first().click());
await S("sched-key-month", async () => { await page.locator("main").click({position:{x:5,y:5}}).catch(()=>{}); await page.keyboard.press("4"); });
await S("sched-add", () => page.getByRole("button", { name: "Add to schedule" }).first().click());
await page.keyboard.press("Escape");
await go(page, "#work/changed");
await S("changed-done", () => page.getByRole("tab", { name: "Done" }).or(page.getByRole("button", { name: "Done", exact: true })).first().click());
await go(page, "#work/handled");
await S("handled-read", () => page.getByRole("tab", { name: /Read, nothing to do/ }).or(page.getByRole("button", { name: /Read, nothing to do/ })).first().click());
await S("handled-reason", () => page.getByRole("button", { name: "Reason", exact: true }).or(page.getByRole("tab", { name: "Reason" })).first().click());
await go(page, "#work/open");
await S("open-questions", () => page.getByRole("tab", { name: /Questions/ }).or(page.getByRole("button", { name: /^Questions/ })).first().click());
await go(page, "#work/open");
await S("open-add", () => page.getByRole("button", { name: /Add a to-do/ }).first().click());
await page.keyboard.press("Escape");
await browser.close();
